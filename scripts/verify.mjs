import {readdirSync} from 'node:fs';
import {resolve} from 'node:path';
const run=(args,cwd=process.cwd())=>{const r=spawnSync(process.execPath,args,{cwd,stdio:'inherit',env:process.env});if(r.status!==0)process.exit(r.status??1)};
run(['node_modules/typescript/bin/tsc','--noEmit','-p','backend']);
run(['node_modules/typescript/bin/tsc','--noEmit','-p','web']);
run(['scripts/check-policy.mjs']);
run(['node_modules/tsx/dist/cli.mjs','--test',...readdirSync('backend/tests').filter(n=>n.endsWith('.test.ts')).map(n=>'backend/tests/'+n)]);
